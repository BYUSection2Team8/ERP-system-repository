#!/usr/bin/env bash
# Builds the two copy-paste files for the Supabase SQL Editor:
#   supabase/paste/1_setup_database.sql  = migrations 001.. + seeds (starter data + 6-month history)
#   supabase/paste/2_run_checks.sql      = every check script (all roll back or are read-only)
# Run from the repo root:  bash supabase/make_paste_files.sh
# (CI runs the same script and tests both files as single batches.)
set -euo pipefail
mkdir -p supabase/paste

checks=(
  supabase/tests/seed_check.sql
  supabase/tests/history_check.sql
  supabase/tests/smoke_core.sql
  supabase/tests/rls_check.sql
  supabase/tests/sales_quote_check.sql
  supabase/tests/production_mrp_check.sql
  supabase/tests/purchasing_check.sql
  supabase/tests/financials_check.sql
  supabase/tests/reports_portal_check.sql
  supabase/tests/tracking_failures_check.sql
  supabase/tests/quotes_printers_capacity_check.sql
  supabase/tests/box_selection_check.sql
  supabase/tests/new_design_check.sql
)

{
  echo "-- ============================================================================="
  echo "-- PASTE 1 of 2: SET UP THE DATABASE (all migrations + starter data + history)"
  echo "-- Supabase -> SQL Editor -> New query -> paste ALL of this -> Run. Run it ONCE."
  echo "-- Generated by supabase/make_paste_files.sh; do not edit by hand."
  echo "-- ============================================================================="
  for f in supabase/migrations/*.sql supabase/seed/*.sql; do
    printf '\n\n-- >>>>>>>>>>>>>>>>>>>> %s\n\n' "$f"
    cat "$f"
  done
  printf "\n\nselect 'DATABASE SET UP: ' || (select count(*) from items) || ' items, ' || (select count(*) from sales_orders) || ' sales orders, inventory \$' || (select balance from v_account_balances where code = '1200') as result;\n"
} > supabase/paste/1_setup_database.sql

{
  echo "-- ============================================================================="
  echo "-- PASTE 2 of 2: CHECK THE DATABASE (every check script)"
  echo "-- Supabase -> SQL Editor -> New query -> paste ALL of this -> Run."
  echo "-- Leaves no test data behind (the tests roll themselves back)."
  echo "-- Success = one row saying ALL CHECKS PASSED. A failure shows an error naming the check."
  echo "-- ============================================================================="
  for f in "${checks[@]}"; do
    printf '\n\n-- >>>>>>>>>>>>>>>>>>>> %s\n\n' "$f"
    cat "$f"
  done
  printf "\n\nselect 'ALL CHECKS PASSED' as result;\n"
} > supabase/paste/2_run_checks.sql

echo "Wrote supabase/paste/1_setup_database.sql and supabase/paste/2_run_checks.sql"
